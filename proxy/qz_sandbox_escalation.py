def _build_correction_note(original_args: str, corrected_args: str) -> str:
    """Describe what changed between raw model arguments and coerced arguments."""
    parts = []
    if "```" in original_args and "```" not in corrected_args:
        parts.append("stripped markdown code fences")
    if ("--- " in original_args or "+++ " in original_args) and "--- " not in corrected_args:
        parts.append("stripped unified diff headers")
    if not parts:
        parts.append("normalised argument structure")
    return ", ".join(parts)


class CorrectionTracker:
    """
    Tracks apply_patch calls where outgoing coercion silently fixed the model's
    output.  On the follow-up request (after Codex runs the corrected call),
    the correction note is appended to the function_call_output so the model
    knows its formatting was fixed.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._pending: dict[str, str] = {}  # call_id → human-readable correction note

    def register(self, call_id: str, original_args: str, corrected_args: str) -> None:
        note = _build_correction_note(original_args, corrected_args)
        with self._lock:
            self._pending[call_id] = note

    def inject_notes(self, input_items: list) -> list:
        """
        Append correction notes to function_call_output items whose call_id
        matches a pending correction.  Returns the (possibly unchanged) list.
        """
        with self._lock:
            if not self._pending:
                return input_items

        result = []
        changed = False
        for item in input_items:
            if not isinstance(item, dict):
                result.append(item)
                continue
            t = item.get("type", "")
            cid = item.get("call_id") or item.get("id") or ""
            if t == "function_call_output" and cid:
                with self._lock:
                    note = self._pending.pop(cid, None)
                if note:
                    output = item.get("output") or ""
                    if isinstance(output, str):
                        suffix = f"\n\n[Proxy auto-corrected apply_patch format: {note}]"
                        result.append(dict(item, output=output + suffix))
                        changed = True
                        continue
            result.append(item)

        return result if changed else input_items


_CORRECTION_TRACKER: Optional[CorrectionTracker] = None
_CORRECTION_TRACKER_LOCK = threading.Lock()


def get_correction_tracker() -> CorrectionTracker:
    global _CORRECTION_TRACKER
    if _CORRECTION_TRACKER is None:
        with _CORRECTION_TRACKER_LOCK:
            if _CORRECTION_TRACKER is None:
                _CORRECTION_TRACKER = CorrectionTracker()
    return _CORRECTION_TRACKER
